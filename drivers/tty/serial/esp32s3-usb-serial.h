#ifndef _ESP32S3_USB_SERIAL_H
#define _ESP32S3_USB_SERIAL_H

#include <linux/bits.h>

#define ESP32S3_USB_SERIAL_EP1		0x00
#define ESP32S3_USB_SERIAL_EP1_CONF	0x04
#define ESP32S3_USB_SERIAL_INT_ST	0x0c
#define ESP32S3_USB_SERIAL_INT_ENA	0x10
#define ESP32S3_USB_SERIAL_INT_CLR	0x14

#define ESP32S3_USB_SERIAL_WR_DONE	BIT(0)
#define ESP32S3_USB_SERIAL_TX_FREE	BIT(1)
#define ESP32S3_USB_SERIAL_RX_AVAIL	BIT(2)

#define ESP32S3_USB_SERIAL_INT_RX	BIT(2)
#define ESP32S3_USB_SERIAL_INT_TX	BIT(3)
#define ESP32S3_USB_SERIAL_INT_MASK	(ESP32S3_USB_SERIAL_INT_RX | \
					 ESP32S3_USB_SERIAL_INT_TX)

#define ESP32S3_USB_SERIAL_FIFO_SIZE	64

/* An absent USB host must never stop kernel progress indefinitely. */
#define ESP32S3_USB_SERIAL_POLL_LIMIT	100000

#endif
